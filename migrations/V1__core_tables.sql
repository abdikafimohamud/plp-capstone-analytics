-- V1__core_tables.sql
-- Core schema for the Real-Time Analytics Platform (Track C).
-- Design notes:
--   * events is RANGE-partitioned by occurred_at (monthly) so old data can be
--     dropped instantly (DROP/DETACH partition) instead of a huge DELETE.
--   * events has NO foreign key to tenants / end_users: ingest throughput matters
--     more than per-row FK checks. The ingest consumer validates tenant + type.
--   * All money is stored as integer minor units (cents).

CREATE EXTENSION IF NOT EXISTS pgcrypto;   -- hmac()/digest() for hashing PII
CREATE EXTENSION IF NOT EXISTS btree_gin;  -- lets a GIN index include tenant_id (used in V6)

-- ---------------------------------------------------------------- dimensions
CREATE TABLE plans (
    plan_id             smallint    PRIMARY KEY,
    name                varchar(50) NOT NULL UNIQUE,
    monthly_price_cents int         NOT NULL CHECK (monthly_price_cents >= 0)
);

CREATE TABLE tenants (
    tenant_id  int         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       varchar(120) NOT NULL,
    plan_id    smallint    NOT NULL REFERENCES plans (plan_id),
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE SEQUENCE end_users_user_id_seq AS bigint;

CREATE TABLE end_users (
    tenant_id           int          NOT NULL REFERENCES tenants (tenant_id),
    user_id             bigint       NOT NULL DEFAULT nextval('end_users_user_id_seq'),
    external_id         varchar(120) NOT NULL,          -- the tenant's own id for the user
    email_hash          bytea,                          -- HMAC-SHA256, never plaintext
    country_code        char(2),
    acquisition_channel varchar(30),
    signup_at           timestamptz  NOT NULL,
    PRIMARY KEY (tenant_id, user_id),
    UNIQUE (tenant_id, external_id)
);

CREATE TABLE event_types (
    event_type_id smallint    PRIMARY KEY,
    name          varchar(60) NOT NULL UNIQUE,
    category      varchar(30) NOT NULL
        CHECK (category IN ('acquisition', 'activation', 'engagement', 'revenue'))
);

-- --------------------------------------------------------------- fact: events
CREATE SEQUENCE events_event_id_seq AS bigint CACHE 1000;

CREATE TABLE events (
    tenant_id     int         NOT NULL,
    event_id      bigint      NOT NULL DEFAULT nextval('events_event_id_seq'),
    user_id       bigint      NOT NULL,
    event_type_id smallint    NOT NULL REFERENCES event_types (event_type_id),
    occurred_at   timestamptz NOT NULL,
    session_id    uuid,
    properties    jsonb       NOT NULL DEFAULT '{}'::jsonb,
    -- a PK on a partitioned table must contain the partition key
    PRIMARY KEY (tenant_id, occurred_at, event_id)
) PARTITION BY RANGE (occurred_at);

-- Safety net: out-of-range events land here instead of failing the ingest.
-- The maintenance job alerts when this partition is not empty.
CREATE TABLE events_default PARTITION OF events DEFAULT;

-- Creates one partition per calendar month (UTC) between p_from and p_to.
CREATE OR REPLACE FUNCTION ensure_events_partitions(p_from date, p_to date)
RETURNS int
LANGUAGE plpgsql AS $$
DECLARE
    m       date := date_trunc('month', p_from)::date;
    created int  := 0;
    part    text;
BEGIN
    WHILE m <= p_to LOOP
        part := format('events_%s', to_char(m, 'YYYY_MM'));
        IF to_regclass(format('%I', part)) IS NULL THEN
            EXECUTE format(
                'CREATE TABLE %I PARTITION OF events FOR VALUES FROM (%L) TO (%L)',
                part,
                (m::timestamp AT TIME ZONE 'UTC'),
                ((m + interval '1 month')::date::timestamp AT TIME ZONE 'UTC'));
            created := created + 1;
        END IF;
        m := (m + interval '1 month')::date;
    END LOOP;
    RETURN created;
END $$;

-- partitions for 4 months back .. 3 months ahead of "today"
SELECT ensure_events_partitions((current_date - interval '4 months')::date,
                                (current_date + interval '3 months')::date);

-- -------------------------------------------------------------------- funnels
CREATE TABLE funnels (
    funnel_id    int          GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id    int          NOT NULL REFERENCES tenants (tenant_id),
    name         varchar(120) NOT NULL,
    window_hours int          NOT NULL DEFAULT 168 CHECK (window_hours > 0),
    UNIQUE (tenant_id, name)
);

CREATE TABLE funnel_steps (
    funnel_id     int      NOT NULL REFERENCES funnels (funnel_id) ON DELETE CASCADE,
    step_order    smallint NOT NULL CHECK (step_order > 0),
    event_type_id smallint NOT NULL REFERENCES event_types (event_type_id),
    PRIMARY KEY (funnel_id, step_order)
);

-- ------------------------------------------------------------------ revenue
CREATE TABLE subscriptions (
    subscription_id bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id       int         NOT NULL,
    user_id         bigint      NOT NULL,
    plan_id         smallint    NOT NULL REFERENCES plans (plan_id),
    status          varchar(20) NOT NULL
        CHECK (status IN ('trialing', 'active', 'past_due', 'canceled')),
    started_at      timestamptz NOT NULL,
    ended_at        timestamptz,
    FOREIGN KEY (tenant_id, user_id) REFERENCES end_users (tenant_id, user_id),
    CHECK (ended_at IS NULL OR ended_at >= started_at)
);

CREATE TABLE payments (
    payment_id      bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subscription_id bigint      NOT NULL REFERENCES subscriptions (subscription_id),
    tenant_id       int         NOT NULL,
    amount_cents    bigint      NOT NULL CHECK (amount_cents > 0),
    currency        char(3)     NOT NULL DEFAULT 'USD',
    status          varchar(20) NOT NULL
        CHECK (status IN ('succeeded', 'failed', 'refunded')),
    paid_at         timestamptz NOT NULL
);

-- -------------------------------------------------------------------- audit
CREATE TABLE audit_log (
    audit_id   bigint      GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    tenant_id  int,                                  -- no FK: audit rows outlive tenants
    table_name varchar(63) NOT NULL,
    operation  char(1)     NOT NULL CHECK (operation IN ('I', 'U', 'D')),
    row_pk     text        NOT NULL,
    old_row    jsonb,
    new_row    jsonb,
    changed_by varchar(63) NOT NULL DEFAULT session_user,
    changed_at timestamptz NOT NULL DEFAULT now()
);
